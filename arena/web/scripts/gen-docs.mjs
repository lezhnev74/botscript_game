// Generates web/src/generated/{templates,docs}.ts from the repo sources of truth:
// engine/lang/bots/*.js (templates and prompt examples), LANGUAGE.md and VISION.md (AI prompt).
// Usage: node scripts/gen-docs.mjs [outDir]   (make gen / make gen-check)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(process.argv[2] ?? join(here, "..", "src", "generated"));
const botsDir = join(here, "..", "..", "engine", "lang", "bots");
const repoRoot = join(here, "..", "..", "..");
const BOTS = [["Rookie", "rookie"], ["Lighthouse", "lighthouse"], ["Tracker", "tracker"], ["Forager", "forager"], ["Hound", "hound"]];

const HEADER = "// Code generated by scripts/gen-docs.mjs. DO NOT EDIT.\n\n";

const read = (p) => readFileSync(p, "utf8");
const lit = (s) => JSON.stringify(s);

const templates =
  HEADER +
  "export interface Template {\n  name: string;\n  source: string;\n}\n\n" +
  "/** The house bots, offered as starting points. */\n" +
  "export const TEMPLATES: Template[] = [\n" +
  BOTS.map(([name, file]) => `  { name: ${lit(name)}, source: ${lit(read(join(botsDir, `${file}.js`)))} },\n`).join("") +
  "];\n";

const docs =
  HEADER +
  `export const LANGUAGE_MD = ${lit(read(join(repoRoot, "LANGUAGE.md")))};\n\n` +
  `export const VISION_MD = ${lit(read(join(repoRoot, "VISION.md")))};\n`;

mkdirSync(out, { recursive: true });
writeFileSync(join(out, "templates.ts"), templates);
writeFileSync(join(out, "docs.ts"), docs);
