package main

import (
	"go/ast"
	"reflect"
	"testing"
)

func TestComplexity(t *testing.T) {
	cases := []struct {
		name string
		body string
		want int
	}{
		{"empty", ``, 1},
		{"if", `if x > 0 { x++ }`, 2},
		{"logical", `if x > 0 && x < 5 || x == 9 { x++ }`, 4},
		{"for", `for i := 0; i < 3; i++ { x++ }`, 2},
		{"range", `for range []int{1} { x++ }`, 2},
		{"switch", `switch x { case 1: x++; case 2, 3: x--; default: x = 0 }`, 3},
		{"select", `select { case <-ch: x++; default: x = 0 }`, 2},
		{"closure counted", `f := func() { if x > 0 { x++ } }; f()`, 2},
		{"arithmetic ignored", `x = x + 1 - 2*3`, 1},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			src := "package p\nfunc f(x int, ch chan int) {\n" + c.body + "\n}\n"
			infos, err := analyzeFile("p/f.go", "f.go", []byte(src))
			if err != nil {
				t.Fatal(err)
			}
			if len(infos) != 1 || infos[0].Complexity != c.want {
				t.Fatalf("got %+v, want complexity %d", infos, c.want)
			}
		})
	}
}

func TestAnalyzeFileNamesAndRanges(t *testing.T) {
	src := "package p\n\ntype T struct{}\n\nfunc (t *T) M() {\n}\n\nfunc F() {}\n"
	infos, err := analyzeFile("p/f.go", "f.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	want := []funcInfo{
		{File: "p/f.go", Name: "T.M", StartLine: 5, StartCol: 1, EndLine: 6, EndCol: 2, Complexity: 1},
		{File: "p/f.go", Name: "F", StartLine: 8, StartCol: 1, EndLine: 8, EndCol: 12, Complexity: 1},
	}
	if !reflect.DeepEqual(infos, want) {
		t.Fatalf("got %+v want %+v", infos, want)
	}
}

func TestAnalyzeFileSyntaxError(t *testing.T) {
	if _, err := analyzeFile("p/f.go", "f.go", []byte("package p\nfunc (")); err == nil {
		t.Fatal("expected error")
	}
}

func TestAnalyzeFileSkipsGenerated(t *testing.T) {
	src := "// Code generated by foo. DO NOT EDIT.\n\npackage p\nfunc F() {}\n"
	infos, err := analyzeFile("p/f.go", "f.go", []byte(src))
	if err != nil || len(infos) != 0 {
		t.Fatalf("generated file must be skipped: %v %v", infos, err)
	}
}

func TestAnalyzeFileGenericReceivers(t *testing.T) {
	src := "package p\n\ntype A[T any] struct{}\ntype B[K comparable, V any] struct{}\n\nfunc (a A[T]) M() {}\nfunc (b *B[K, V]) N() {}\n"
	infos, err := analyzeFile("p/f.go", "f.go", []byte(src))
	if err != nil || len(infos) != 2 || infos[0].Name != "A.M" || infos[1].Name != "B.N" {
		t.Fatalf("got %+v %v", infos, err)
	}
	if got := recvName(&ast.ArrayType{}); got != "?" {
		t.Fatalf("got %q", got)
	}
}

func TestAnalyzeFileSkipsBuildIgnore(t *testing.T) {
	src := "//go:build ignore\n\npackage main\n\nfunc F() {}\n"
	infos, err := analyzeFile("p/f.go", "f.go", []byte(src))
	if err != nil || len(infos) != 0 {
		t.Fatalf("ignored file must be skipped: %v %v", infos, err)
	}
}
