func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, content := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func runIn(root string) (int, string) {
	var out, errb bytes.Buffer
	code := run([]string{"-root", root, "-profile", filepath.Join(root, "cover.out")}, &out, &errb)
	return code, out.String() + errb.String()
}

const complexSrc = `package bad

func Tangled(x int) int {
	if x > 1 { x++ }
	if x > 2 { x++ }
	if x > 3 { x++ }
	if x > 4 { x++ }
	if x > 5 { x++ }
	if x > 6 { x++ }
	if x > 7 { x++ }
	if x > 8 { x++ }
	return x
}
`

// Red proof: a planted complex untested function makes the gate fail.
func TestRunFailsOnComplexUntestedFunction(t *testing.T) {
	root := writeTree(t, map[string]string{
		"go.mod":     "module example.com/x\n\ngo 1.26\n",
		"bad/bad.go": complexSrc,
		"cover.out":  "mode: set\nexample.com/x/bad/bad.go:3.24,12.2 9 0\n",
	})
	code, out := runIn(root)
	if code != 1 || !strings.Contains(out, "Tangled") {
		t.Fatalf("code=%d out=%q", code, out)
	}
}

